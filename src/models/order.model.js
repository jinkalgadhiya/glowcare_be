const mongoose = require("mongoose");

// ================= ORDER ITEM SCHEMA =================

const orderItemSchema = new mongoose.Schema(
  {
    productId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "Product",
      required: true,
    },

    variantId: {
      type: String,
      default: "",
    },

    name: {
      type: String,
      required: true,
      trim: true,
    },

    image: {
      type: String,
      default: "",
    },

    category: {
      type: String,
      default: "",
    },

    size: {
      type: String,
      default: "",
    },

    price: {
      type: Number,
      required: true,
      min: 0,
    },

    quantity: {
      type: Number,
      required: true,
      min: 1,
    },

    total: {
      type: Number,
      required: true,
      min: 0,
    },
  },
  {
    _id: false,
  },
);

// ================= ORDER SCHEMA =================

const orderSchema = new mongoose.Schema(
  {
    // ================= USER =================

    userId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "User",
      required: true,
    },

    // ================= ORDER =================

    orderNumber: {
      type: String,
      required: true,
      unique: true,
      trim: true,
    },

    items: {
      type: [orderItemSchema],
      required: true,
      validate: {
        validator: (items) => Array.isArray(items) && items.length > 0,
        message: "Order must contain at least one product",
      },
    },

    // ================= CUSTOMER =================

    customer: {
      fullName: {
        type: String,
        required: true,
        trim: true,
      },

      email: {
        type: String,
        required: true,
        lowercase: true,
        trim: true,
      },

      contactNumber: {
        type: String,
        default: "",
        trim: true,
      },
    },

    // ================= SHIPPING =================

    shippingAddress: {
      fullName: {
        type: String,
        required: true,
        trim: true,
      },

      contactNumber: {
        type: String,
        required: true,
        trim: true,
      },

      address: {
        type: String,
        required: true,
        trim: true,
      },

      city: {
        type: String,
        required: true,
        trim: true,
      },

      state: {
        type: String,
        required: true,
        trim: true,
      },

      pincode: {
        type: String,
        required: true,
        trim: true,
      },
    },

    // ================= PRICING =================

    pricing: {
      subtotal: {
        type: Number,
        required: true,
        min: 0,
      },

      discount: {
        type: Number,
        default: 0,
        min: 0,
      },

      gst: {
        type: Number,
        default: 0,
        min: 0,
      },

      shipping: {
        type: Number,
        default: 0,
        min: 0,
      },

      total: {
        type: Number,
        required: true,
        min: 0,
      },

      couponCode: {
        type: String,
        default: "",
        trim: true,
        uppercase: true,
      },

      couponDiscount: {
        type: Number,
        default: 0,
        min: 0,
      },
    },

    // ================= DELIVERY =================

    deliveryMethod: {
      type: String,
      enum: ["Standard", "Express"],
      default: "Standard",
    },

    // ================= PAYMENT =================

    paymentMethod: {
      type: String,
      enum: ["COD", "Online"],
      default: "COD",
    },

    paymentStatus: {
      type: String,
      enum: ["Pending", "Paid", "Failed", "Refunded"],
      default: "Pending",
    },

    // Razorpay order created on the server
    razorpayOrderId: {
      type: String,
      default: null,
      trim: true,
    },

    // Razorpay payment ID received after successful checkout
    razorpayPaymentId: {
      type: String,
      default: null,
      trim: true,
    },

    // Signature generated by Razorpay and verified by backend
    razorpaySignature: {
      type: String,
      default: null,
      trim: true,
    },

    // Date and time when payment was successfully verified
    paidAt: {
      type: Date,
      default: null,
    },

    // ================= ORDER STATUS =================

    status: {
      type: String,
      enum: [
        "Pending",
        "Confirmed",
        "Processing",
        "Shipped",
        "Delivered",
        "Cancelled",
      ],
      default: "Pending",
    },

    orderDate: {
      type: Date,
      default: Date.now,
    },
  },
  {
    timestamps: true,
  },
);

const Orders = mongoose.model("Order", orderSchema);

module.exports = Orders;